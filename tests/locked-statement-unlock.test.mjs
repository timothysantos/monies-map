test("the error report an import failure records hides a password held in memory", async () => {
  const { previewImportBatch } = await import("../src/client/import-api.js");
  const secret = "REPORTEDCARD5566";
  const release = holdSecret(secret);
  const requests = [];
  const originalFetch = globalThis.fetch;
  globalThis.fetch = async (url, init) => {
    requests.push({ url: String(url), body: String(init?.body ?? "") });
    if (String(url).endsWith("/api/imports/preview")) {
      return new Response(`Internal error near ${secret}`, { status: 500, headers: { "content-type": "text/plain" } });
    }
    return new Response(JSON.stringify({ diagnosticId: "diag-1" }), { status: 200, headers: { "content-type": "application/json" } });
  };
  try {
    await assert.rejects(previewImportBatch({
      sourceLabel: "locked.pdf",
      sourceType: "pdf",
      rows: [],
      defaultAccountName: "UOB One",
      ownerName: "Tim",
      statementCheckpoints: [],
      // Even a context that carried the password by mistake is scrubbed.
      diagnosticContext: { source: "import_preview", action: `Preview import ${secret}`, requestContext: { note: secret, quoted: `"${secret}"` } }
    }));
  } finally {
    globalThis.fetch = originalFetch;
    release();
  }
  const report = requests.find((request) => request.url.endsWith("/api/error-diagnostics/record"));
  assert.ok(report, "a report was recorded");
  assert.equal(report.body.includes(secret), false);
  assert.match(report.body, /\[hidden\]/);
});

