test("the password never appears in a serialised error, a log call, a request, or browser storage", async () => {
  const secret = "SECRETCARD99887766";
  const leaks = [];
  const seen = (label, value) => {
    const text = typeof value === "string" ? value : JSON.stringify(value);
    if (String(text).includes(secret)) leaks.push(label);
  };
  const originals = {};
  for (const method of ["log", "info", "warn", "error", "debug"]) {
    originals[method] = console[method];
    console[method] = (...args) => seen(`console.${method}`, args.map(String).join(" "));
  }
  const originalFetch = globalThis.fetch;
  globalThis.fetch = async (...args) => { seen("fetch", args); return new Response("{}"); };
  const store = () => ({ setItem: (key, value) => seen("storage", [key, value]), getItem: () => null, removeItem() {}, clear() {} });
  const descriptors = {};
  const defineGlobal = (name, value) => {
    descriptors[name] = Object.getOwnPropertyDescriptor(globalThis, name);
    Object.defineProperty(globalThis, name, { value, configurable: true, writable: true });
  };
  defineGlobal("localStorage", store());
  defineGlobal("sessionStorage", store());
  defineGlobal("indexedDB", { open: (...args) => { seen("indexedDB.open", args); throw new Error("blocked"); } });

  const errors = [];
  try {
    // A wrong try, then the right password, a skipped file, and a corrupt file.
    const prompt = scriptedPrompt([{ password: secret + "X", useForBatch: false }, { password: secret, useForBatch: true }]);
    const file = lockedFile();
    attachPdfUnlocker(file, createPdfUnlocker({ fileName: "locked.pdf", askPassword: prompt.askPassword, setBatchPassword: () => {} }));
    await openLockedPdf({ pdfjs: fakePdfjs({ password: secret }), file, code: PASSWORD_NEEDED });
    for (const request of prompt.requests) seen("prompt request", request);

    const skipFile = lockedFile("skip.pdf");
    attachPdfUnlocker(skipFile, createPdfUnlocker({ fileName: "skip.pdf", askPassword: async () => null }));
    await openLockedPdf({ pdfjs: fakePdfjs({ password: secret }), file: skipFile, code: PASSWORD_NEEDED }).catch((error) => errors.push(error));
    await openLockedPdf({ pdfjs: fakePdfjs({ password: secret }), file: lockedFile(), code: PASSWORD_NEEDED }).catch((error) => errors.push(error));
    const bad = lockedFile("bad.pdf");
    attachPdfUnlocker(bad, createPdfUnlocker({ fileName: "bad.pdf", askPassword: async () => ({ password: secret, useForBatch: false }) }));
    await openLockedPdf({ pdfjs: fakePdfjs({ failWith: new Error("Invalid PDF structure.") }), file: bad, code: PASSWORD_NEEDED }).catch((error) => errors.push(error));
    for (const error of errors) {
      seen("error message", error.message);
      seen("error stack", error.stack);
      seen("error json", { ...error });
    }
  } finally {
    for (const [method, original] of Object.entries(originals)) console[method] = original;
    globalThis.fetch = originalFetch;
    for (const [name, descriptor] of Object.entries(descriptors)) {
      if (descriptor) Object.defineProperty(globalThis, name, descriptor);
      else delete globalThis[name];
    }
  }
  assert.equal(errors.length, 3);
  assert.deepEqual(leaks, []);
});

test("a crash or diagnostic report redacts a password held in memory, and forgets it once released", () => {
  const secret = "REPORTCARD11223344";
  const release = holdSecret(secret);
  const crash = buildCrashReport({
    kind: "render",
    level: "screen",
    error: Object.assign(new Error(`Could not open with ${secret}`), { stack: `Error: ${secret}\n at open` }),
    componentStack: `in Dialog(${secret})`,
    location: { pathname: "/imports", search: "" },
    userAgent: `UA ${secret}`
  });
  assert.equal(JSON.stringify(crash).includes(secret), false);
  assert.match(crash.errorMessage, /Could not open with/);
  assert.equal(redactSecrets(`x ${secret} y ${secret}`), "x [hidden] y [hidden]");
  release();
  assert.equal(redactSecrets(`kept ${secret}`), `kept ${secret}`);
  // Negative: an empty password never hides every empty string.
  holdSecret("")();
  assert.equal(redactSecrets("plain text"), "plain text");
});

test("the encrypted statement text opens with the right password and reads exactly as the unlocked file, and the parser gives the same rows", async () => {
  const plain = await pdfjs.getDocument({ data: fixtureBytes("uob-one-savings-apr-2026.plain.pdf"), verbosity: 0 }).promise;
  const plainText = await extractTextFromPdfDocument(plain);
  const plainParsed = parseStatementText(plainText, "uob-one-apr-2026.pdf");
  assert.equal(plainParsed.parserKey, "uob_savings_pdf");
  assert.equal(plainParsed.rows.length, 4);
  assert.deepEqual(plainParsed.rows.map((row) => row.date), ["2026-04-03", "2026-04-15", "2026-04-20", "2026-04-30"]);
  assert.equal(plainParsed.checkpoints[0].statementBalanceMinor, 929509);

  for (const name of ["locked-aes-128", "locked-rc4-128"]) {
    const file = fixtureFile(`uob-one-savings-apr-2026.${name}.pdf`);
    const prompt = scriptedPrompt([{ password: "NOT-THE-PASSWORD", useForBatch: false }, { password: PASSWORD, useForBatch: false }]);
    attachPdfUnlocker(file, createPdfUnlocker({ fileName: file.name, askPassword: prompt.askPassword }));
    const document = await openLockedPdf({ pdfjs, file, code: PASSWORD_NEEDED });
    const text = await extractTextFromPdfDocument(document);
    assert.equal(text, plainText, `${name} reads as the unlocked file`);
    assert.deepEqual(parseStatementText(text, "uob-one-apr-2026.pdf").rows, plainParsed.rows);
    assert.deepEqual(prompt.requests.map((request) => request.wrong), [false, true]);
  }
});

